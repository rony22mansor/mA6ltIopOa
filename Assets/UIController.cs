using UnityEngine;
using UnityEngine.UI; // ????? ??????? ?? ????? ???????
using TMPro; // ????? ??? ??? ?????? TextMeshPro

public class UIController : MonoBehaviour
{
    // ???? ???? ??? MassSpringSystem ??? ??? ????? ?? Inspector
    public MassSpringSystem massSpringSystem;

    [Header("UI Elements")]
    public Slider stiffnessSlider;
    public Slider dampingSlider;
    public Slider gravitySlider;
    public Toggle fixTopToggle;

    // ???????: ???? ???? ????? ???????
    [Header("Value Labels")]
    public TextMeshProUGUI stiffnessValueText;
    public TextMeshProUGUI dampingValueText;
    public TextMeshProUGUI gravityValueText;


    void Start()
    {
        // ?????? ?? ?? massSpringSystem ?????
        if (massSpringSystem == null)
        {
            // ?????? ?????? ???????? ??? ?? ??? ??????
            massSpringSystem = FindObjectOfType<MassSpringSystem>();
            if (massSpringSystem == null)
            {
                Debug.LogError("MassSpringSystem not found in the scene!");
                return;
            }
        }

        // 1. ????? ????? ??????? ??? Sliders ?? ???????
        stiffnessSlider.value = massSpringSystem.stiffness;
        dampingSlider.value = massSpringSystem.damping;
        gravitySlider.value = massSpringSystem.gravity;
        fixTopToggle.isOn = massSpringSystem.isFixedTop;

        // ????? ?????? ?????? ???????
        UpdateLabels();

        // 2. ??? ??????? (Events)
        // ??? ????? ???? ??? Slider? ???? ??????? ?????? ???????
        stiffnessSlider.onValueChanged.AddListener(UpdateStiffness);
        dampingSlider.onValueChanged.AddListener(UpdateDamping);
        gravitySlider.onValueChanged.AddListener(UpdateGravity);
        fixTopToggle.onValueChanged.AddListener(UpdateFixTop);
    }

    // ???? ??????? ???? ???? ????????? ?? ????? ???????
    public void UpdateStiffness(float value)
    {
        massSpringSystem.stiffness = value;
        UpdateLabels();
    }

    public void UpdateDamping(float value)
    {
        massSpringSystem.damping = value;
        UpdateLabels();
    }

    public void UpdateGravity(float value)
    {
        massSpringSystem.gravity = value;
        UpdateLabels();
    }

    public void UpdateFixTop(bool value)
    {
        massSpringSystem.isFixedTop = value;
        // ??????: ??? ?????? ????? ????? ????? ?????? ????? ???? ????
        // ???? ??? ?????? ?? ???? Start() ??? ?? ????? ??????
        // ??? ???? ?????? ??? ????? MassSpringSystem
    }

    // ???? ?????? ?????? ???? ???? ?????
    private void UpdateLabels()
    {
        if (stiffnessValueText != null) stiffnessValueText.text = massSpringSystem.stiffness.ToString("F2");
        if (dampingValueText != null) dampingValueText.text = massSpringSystem.damping.ToString("F2");
        if (gravityValueText != null) gravityValueText.text = massSpringSystem.gravity.ToString("F2");
    }
}